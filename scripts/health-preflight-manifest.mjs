import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

// A DB registry entry alone cannot attest the safety of a legacy deployment.
// Only a direct early OPTIONS return before business code is eligible.
// A mention in a comment, string, unreachable/late branch is not a contract.
// CI makes changes to this source-derived contract
// reviewable; runtime never guesses safety or sends a business fallback.
export function hasEarlyPreflight(sourceText) {
  const file = ts.createSourceFile('index.ts', sourceText, ts.ScriptTarget.Latest, true);
  let eligible = false;
  const noCalls = node => {
    if (ts.isCallExpression(node) || ts.isNewExpression(node) || ts.isAwaitExpression(node)
      || ts.isDeleteExpression(node) || ts.isPostfixUnaryExpression(node)
      || (ts.isPrefixUnaryExpression(node) && [ts.SyntaxKind.PlusPlusToken, ts.SyntaxKind.MinusMinusToken].includes(node.operator))
      || (ts.isBinaryExpression(node) && node.operatorToken.kind >= ts.SyntaxKind.FirstAssignment
        && node.operatorToken.kind <= ts.SyntaxKind.LastAssignment)) return false;
    let safe = true; ts.forEachChild(node, child => { if (!noCalls(child)) safe = false; }); return safe;
  };
  const resolveHandler = node => {
    if (!node || !ts.isIdentifier(node)) return node;
    for (const s of file.statements) {
      if (ts.isVariableStatement(s) && (s.declarationList.flags & ts.NodeFlags.Const)) for (const d of s.declarationList.declarations)
        if (ts.isIdentifier(d.name) && d.name.text === node.text) return d.initializer;
    }
    return null;
  };
  const safeHandler = handler => {
    if (!handler || !handler.body || !ts.isBlock(handler.body)) return false;
    const name = handler.parameters?.[0]?.name;
    if (!name || !ts.isIdentifier(name)) return false;
    for (const statement of handler.body.statements) {
      // Object constants and non-calling log arguments cannot mutate customers.
      if (ts.isVariableStatement(statement) && (statement.declarationList.flags & ts.NodeFlags.Const)
        && noCalls(statement)) continue;
      if (ts.isExpressionStatement(statement) && ts.isCallExpression(statement.expression)
        && statement.expression.expression.getText(file) === 'console.log'
        && statement.expression.arguments.every(noCalls)) continue;
      if (!ts.isIfStatement(statement)) return false;
      const c = statement.expression;
      if (!ts.isBinaryExpression(c) || c.operatorToken.kind !== ts.SyntaxKind.EqualsEqualsEqualsToken
        || !ts.isPropertyAccessExpression(c.left) || c.left.expression.getText(file) !== name.text
        || c.left.name.text !== 'method' || !ts.isStringLiteral(c.right) || c.right.text !== 'OPTIONS') return false;
      const branch = statement.thenStatement;
      const ret = ts.isBlock(branch) && branch.statements.length === 1 ? branch.statements[0] : branch;
      if (!ts.isReturnStatement(ret) || !ret.expression || !ts.isNewExpression(ret.expression)
        || ret.expression.expression.getText(file) !== 'Response') return false;
      return [...(ret.expression.arguments ?? [])].every(noCalls);
    }
    return false;
  };
  // Exactly one actual top-level entrypoint. A dead nested serve must not
  // certify a different unsafe handler. Mutable handler aliases are rejected.
  const entrypoints = file.statements.filter(s => ts.isExpressionStatement(s)
    && ts.isCallExpression(s.expression) && ['serve', 'Deno.serve'].includes(s.expression.expression.getText(file)));
  if (entrypoints.length === 1) eligible = safeHandler(resolveHandler(entrypoints[0].expression.arguments[0]));
  return eligible;
}

export function buildManifest() {
const root = resolve('supabase/functions');
const sources = readdirSync(root).sort().flatMap(name => {
  const entry = resolve(root, name, 'index.ts');
  if (!existsSync(entry)) return [];
  const source = readFileSync(entry, 'utf8');
  return hasEarlyPreflight(source) ? [{ name, source }] : [];
});
const digest = createHash('sha256').update(JSON.stringify(sources)).digest('hex');
const content = '// Generated by scripts/health-preflight-manifest.mjs; do not edit.\n'
  + `export const PREFLIGHT_SOURCE_DIGEST = ${JSON.stringify(digest)};\n`
  + `export const PREFLIGHT_FUNCTIONS = new Set<string>(${JSON.stringify(sources.map(s => s.name), null, 2)});\n`;
const destination = resolve(root, 'system-health-full-check/preflight-manifest.generated.ts');
if (process.argv.includes('--check')) {
  if (!existsSync(destination) || readFileSync(destination, 'utf8') !== content) throw new Error('Health preflight manifest is stale; regenerate and review source changes');
} else writeFileSync(destination, content);
console.log(`Health preflight source contracts: ${sources.length}; ${process.argv.includes('--check') ? 'PASS' : 'generated'}`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) buildManifest();
