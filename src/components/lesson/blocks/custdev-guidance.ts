export function getCustdevGuidance(label: string): Guidance | undefined {
  const question = /^Вопрос ([1-7])\.\d+$/.exec(label);
  if (question) {
    return {
      explanation:
        "Напишите открытый вопрос о реальном опыте человека. Не подсказывайте ответ. Отметьте ниже типы респондентов, которым подходит этот вопрос.",
      example: questionExamples[Number(question[1]) - 1],
    };
  }
  if (label.startsWith("Комментарий к вопросу ")) {
    return {
      explanation:
        "Необязательная заметка для себя: что хотите выяснить или о чём спросить дополнительно. Это не ответ респондента.",
    };
  }
  return fields[
    label === "Ручная поправка повторяемости" ? "Повторяемость" : label
  ];
}
