
-- 1. Create secure RPC function for creating positions (with normalization + anti-duplicate + audit)
CREATE OR REPLACE FUNCTION public.create_position_catalog_entry(p_label text)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_normalized text;
  v_code text;
  v_existing_id uuid;
  v_new_id uuid;
BEGIN
  -- Normalize: trim, collapse spaces, lowercase
  v_normalized := lower(trim(regexp_replace(p_label, '\s+', ' ', 'g')));
  
  IF v_normalized = '' THEN
    RAISE EXCEPTION 'Название должности не может быть пустым';
  END IF;
  
  -- Generate code: spaces to underscores, keep hyphens, remove other special chars
  v_code := regexp_replace(v_normalized, '[^a-zа-яёіўґєїабвгдежзийклмнопрстуфхцчшщъыьэюя0-9\-_ ]', '', 'g');
  v_code := regexp_replace(v_code, '\s+', '_', 'g');
  
  -- Check for existing entry (by normalized label)
  SELECT id INTO v_existing_id
  FROM legal_details_positions_catalog
  WHERE lower(trim(regexp_replace(label, '\s+', ' ', 'g'))) = v_normalized
  LIMIT 1;
  
  IF v_existing_id IS NOT NULL THEN
    -- Reactivate if inactive
    UPDATE legal_details_positions_catalog
    SET is_active = true
    WHERE id = v_existing_id AND is_active = false;
    
    RETURN v_existing_id;
  END IF;
  
  -- Check by code too (belt-and-suspenders)
  SELECT id INTO v_existing_id
  FROM legal_details_positions_catalog
  WHERE code = v_code
  LIMIT 1;
  
  IF v_existing_id IS NOT NULL THEN
    UPDATE legal_details_positions_catalog
    SET is_active = true
    WHERE id = v_existing_id AND is_active = false;
    
    RETURN v_existing_id;
  END IF;
  
  -- Insert new entry
  INSERT INTO legal_details_positions_catalog (code, label, is_system, is_active, sort_order)
  VALUES (v_code, trim(regexp_replace(p_label, '\s+', ' ', 'g')), false, true, 999)
  RETURNING id INTO v_new_id;
  
  -- Audit log
  INSERT INTO audit_logs (action, actor_type, actor_user_id, meta)
  VALUES (
    'position_catalog_entry_created',
    'user',
    auth.uid(),
    jsonb_build_object('position_id', v_new_id, 'label', trim(regexp_replace(p_label, '\s+', ' ', 'g')), 'code', v_code)
  );
  
  RETURN v_new_id;
END;
$$;

